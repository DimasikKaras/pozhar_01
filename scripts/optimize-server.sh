#!/bin/bash
# ==============================================================================
# Скрипт диагностики и очистки дискового пространства сервера PozhNadzor
# ==============================================================================

set -e

echo "=================================================="
echo "📊 1. ДИАГНОСТИКА СИСТЕМЫ И ДИСКОВОГО ПРОСТРАНСТВА"
echo "=================================================="

echo -e "\n💾 Использование диска (df -h):"
df -h /

echo -e "\n🧠 Использование оперативной памяти и Swap (free -m):"
free -m

echo -e "\n🐳 Использование диска Docker (docker system df):"
docker system df 2>/dev/null || echo "Docker демон не запущен или недоступен"

echo -e "\n📁 Размер каталога бэкапов (./backups):"
du -sh ./backups 2>/dev/null || du -sh /opt/pozhnadzor/backups 2>/dev/null || echo "Каталог backups не найден"

echo -e "\n=================================================="
echo "🧹 2. БЕЗОПАСНАЯ ОЧИСТКА МУСОРА И КЭША DOCKER"
echo "=================================================="
echo "Очистка удаляет:"
echo " - Старый кэш сборки (build cache)"
echo " - Зависшие промежуточные образы (<none>)"
echo " - Старые неиспользуемые сетевые и лог-файлы"
echo "ВАЖНО: Именованный том базы данных (postgres_data) НЕ ЗАДЕВАЕТСЯ!"
echo ""

# Очистка кэша сборщика BuildKit
echo "Очистка кэша сборки Docker..."
docker builder prune -a -f || true

# Очистка неиспользуемых образов и контейнеров
echo "Очистка неиспользуемых контейнеров и слоев..."
docker system prune -f || true

# Очистка старых логов Docker, если они разрослись
echo "Усечение тяжелых логов контейнеров..."
find /var/lib/docker/containers/ -type f -name "*.log" -exec truncate -s 0 {} + 2>/dev/null || true

echo -e "\n=================================================="
echo "✅ ОЧИСТКА ЗАВЕРШЕНА! Текущее состояние диска:"
echo "=================================================="
df -h /
docker system df 2>/dev/null || true

echo -e "\n🚀 Теперь вы можете быстро запустить проект:"
echo "docker compose up -d"
